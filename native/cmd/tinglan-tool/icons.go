package main

import (
	"fmt"
	"io"
	"os"
	"path/filepath"

	"tinglan/native/internal/appmeta"
)

// iconsCommand regenerates the compiled icon set and the display-name constants
// from the committed SVG sources. It is the Go replacement for
// native/scripts/generate-assets.mjs: the SVGs under native/assets/lucide are
// the source of truth, and no Node.js runtime is involved.
func iconsCommand(stdout, stderr io.Writer, args []string) error {
	root, err := repoRoot()
	if err != nil {
		return err
	}
	native := filepath.Join(root, "native")
	sources := filepath.Join(native, "assets", "lucide")
	target := filepath.Join(native, "internal", "icons", "icons.go")
	goBin := goBinary()
	compile := commandSpec{Dir: native, Name: goBin, Args: []string{"run", "./tools/icons", sources, target}}
	if err := runCommand(compile, stdout, stderr); err != nil {
		return fmt.Errorf("compile icons: %w", err)
	}
	nameFile := filepath.Join(native, "cmd", "music", "app_name.go")
	generated := fmt.Sprintf(`// Code generated by tinglan-tool icons. DO NOT EDIT.
package main

const appDisplayName = %q
const appBrandLabel = %q
`, appmeta.DisplayName, appmeta.BrandLabel)
	if err := os.WriteFile(nameFile, []byte(generated), 0o644); err != nil {
		return err
	}
	for _, name := range []string{"icon.png", "tray.png", "icon.LICENSE.txt"} {
		if err := copyFile(filepath.Join(root, "build", name), filepath.Join(native, "internal", "icons", name)); err != nil {
			return err
		}
	}
	_, err = fmt.Fprintf(stdout, "icons: compiled %s and refreshed %s\n", target, nameFile)
	return err
}
